def get_json(url: str):
    with urllib.request.urlopen(url, timeout=30) as r:
        return json.load(r)


def kv_mb(cfg: dict) -> int:
    cfg = cfg.get("text_config", cfg)
    layers = cfg["num_hidden_layers"]
    heads = cfg["num_attention_heads"]
    kv_heads = cfg.get("num_key_value_heads", heads)
    head_dim = cfg.get("head_dim") or cfg["hidden_size"] // heads
    return int(2 * layers * kv_heads * head_dim * CTX * KV_BYTES / 2**20)


def main():
    print(f"# LLM catalog: id, name, file size MB, VRAM MB at {CTX} ctx (q8_0 KV), url, sha256, note, note (ru).")
    print("# Generated by server/build_catalog.py; do not edit by hand.")
    for cid, name, repo, fname, cfg_repo, note, note_ru in MODELS:
        tree = get_json(f"https://huggingface.co/api/models/{repo}/tree/main")
        entry = next(f for f in tree if f["path"] == fname)
        size_mb = entry["size"] // 2**20
        sha = entry.get("lfs", {}).get("oid", "")
        cfg = get_json(f"https://huggingface.co/{cfg_repo}/resolve/main/config.json")
        vram = size_mb + kv_mb(cfg) + OVERHEAD_MB
        url = f"https://huggingface.co/{repo}/resolve/main/{fname}"
        print("\t".join([cid, name, str(size_mb), str(vram), url, sha, note, note_ru]))
        print(f"{cid}: {size_mb} MB file, {vram} MB VRAM", file=sys.stderr)


if __name__ == "__main__":
    main()
